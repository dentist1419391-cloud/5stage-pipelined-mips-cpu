`timescale 1ns/1ps

module Instruction_memory(
    
    input [31:0] PC,
    output [31:0] Instruction_IF
);
    
    reg [31:0] inst_mem [0:255];
    initial begin

    // =====================================================
    // EX/MEM Forwarding
    // =====================================================

    // PC0 : add $1,$2,$3
    // $1 = 9 + 10 = 19
    inst_mem[0] = 32'b00000000010000110000100000100000;

    // PC4 : sub $4,$1,$3
    // $4 = 19 - 10 = 9
    // EX/MEM Forwarding
    inst_mem[1] = 32'b00000000001000110010000000100010;


    // =====================================================
    // MEM/WB Forwarding
    // =====================================================

    // PC8 : add $1,$2,$3
    // $1 = 19
    inst_mem[2] = 32'b00000000010000110000100000100000;

    // PC12 : nop
    inst_mem[3] = 32'b00000000000000000000000000000000;

    // PC16 : sub $4,$1,$3
    // $4 = 19 - 10 = 9
    // MEM/WB Forwarding
    inst_mem[4] = 32'b00000000001000110010000000100010;


    // =====================================================
    // Forwarding Priority
    // EX/MEM > MEM/WB
    // =====================================================

    // PC20 : add $1,$2,$3
    // $1 = 19
    inst_mem[5] = 32'b00000000010000110000100000100000;

    // PC24 : sub $1,$5,$6
    // $1 = 12 - 6 = 6
    inst_mem[6] = 32'b00000000101001100000100000100010;

    // PC28 : add $4,$1,$7
    // $4 = 6 + 3 = 9
    // EX/MEM 값($1=6)이 MEM/WB 값($1=19)보다 우선
    inst_mem[7] = 32'b00000000001001110010000000100000;


    // =====================================================
    // Branch Not Taken
    // =====================================================

    // PC32 : beq $10,$11,4
    // $10=4, $11=1 → Not Taken
    inst_mem[8] = 32'b00010001010010110000000000000100;

    // PC36 : addi $1,$2,30
    // $1 = 9 + 30 = 39
    inst_mem[9] = 32'b00100000010000010000000000011110;

    // PC40 : slt $1,$2,$3
    // 9 < 10 → $1 = 1
    inst_mem[10] = 32'b00000000010000110000100000101010;


    // =====================================================
    // Branch Taken
    // =====================================================

    // PC44 : beq $10,$10,4
    //
    // target = PC+4 + (4<<2)
    //        = 48 + 16
    //        = PC64
    inst_mem[11] = 32'b00010001010010100000000000000100;

    // PC48 : addi $1,$2,30
    // Branch Taken으로 ID/EX Flush
    inst_mem[12] = 32'b00100000010000010000000000011110;

    // PC52 : slt $1,$2,$3
    // Branch Taken으로 IF/ID Flush
    inst_mem[13] = 32'b00000000010000110000100000101010;

    // PC56 : Branch 때문에 Fetch되지 않음
    inst_mem[14] = 32'b00000000000000000000000000000000;

    // PC60 : Branch 때문에 Fetch되지 않음
    inst_mem[15] = 32'b00000000000000000000000000000000;


    // =====================================================
    // Branch Target
    // =====================================================

    // PC64 : addi $8,$0,88
    // $8 = 88
    inst_mem[16] = 32'b00100000000010000000000001011000;


    // =====================================================
    // Jump
    // =====================================================

    // PC68 : j 20
    // target field = 20
    // Jump_PC = 20 << 2 = PC80
    inst_mem[17] = 32'b00001000000000000000000000010100;

    // PC72 : add $1,$2,$3
    // Jump 때문에 IF/ID Flush
    inst_mem[18] = 32'b00000000010000110000100000100000;

    // PC76 : sub $1,$2,$3
    // Jump 때문에 애초에 Fetch되지 않아야 함
    inst_mem[19] = 32'b00000000010000110000100000100010;


    // =====================================================
    // Jump Target
    // =====================================================

    // PC80 : addi $12,$0,12
    // $12 = 12
    inst_mem[20] = 32'b00100000000011000000000000001100;
    
    // PC80 : addi $12,$0,12
    
    
    // PC84 : lw $6,400($0)
    inst_mem[21] = 32'h8C060190;
    
    // PC88 : add $7,$5,$6
    inst_mem[22] = 32'h00A63820;
    
    // PC92 : addi $13,$0,13
    inst_mem[23] = 32'h200D000D;

    end
    assign Instruction_IF= inst_mem[PC>>2];

endmodule